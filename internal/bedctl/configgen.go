// AgentPort extracts the port from an addr like ":9091" or "0.0.0.0:9091".
func AgentPort(addr string) (uint16, error) {
	p := addr
	if i := strings.LastIndex(p, ":"); i >= 0 {
		p = p[i+1:]
	}
	n, err := strconv.Atoi(p)
	if err != nil || n <= 0 || n > 65535 {
		return 0, fmt.Errorf("无法从监听地址 %q 解析端口", addr)
	}
	return uint16(n), nil
}

// setYAMLValue edits a nested scalar key (e.g. server.port, addr) in place,
// preserving comments and unrelated content via a yaml.Node round-trip.
// Indentation is kept at 2 spaces to match the generated config layout.
func setYAMLValue(path string, newValue string, keyPath ...string) error {
	data, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	var doc yaml.Node
	if err := yaml.Unmarshal(data, &doc); err != nil {
		return fmt.Errorf("解析 %s: %w", path, err)
	}
	if len(doc.Content) == 0 {
		return fmt.Errorf("%s 不是有效的 YAML 映射", path)
	}
	node := doc.Content[0]
	for i, key := range keyPath {
		last := i == len(keyPath)-1
		if node.Kind != yaml.MappingNode {
			return fmt.Errorf("%s: %s 不是映射，无法修改", path, key)
		}
		var child *yaml.Node
		for j := 0; j+1 < len(node.Content); j += 2 {
			if node.Content[j].Value == key {
				child = node.Content[j+1]
				break
			}
		}
		if child == nil {
			if !last {
				return fmt.Errorf("%s 缺少 %s 段，无法修改", path, strings.Join(keyPath, "."))
			}
			// Append the missing final key; yaml.v3 emits the mapping's indent.
			tag, style := scalarTagAndStyle(newValue)
			node.Content = append(node.Content,
				&yaml.Node{Kind: yaml.ScalarNode, Value: key, Tag: "!!str"},
				&yaml.Node{Kind: yaml.ScalarNode, Value: newValue, Tag: tag, Style: style},
			)
			break
		}
		if last {
			tag, style := scalarTagAndStyle(newValue)
			child.Value = newValue
			child.Tag = tag
			child.Style = style
		} else {
			node = child
		}
	}
	var out bytes.Buffer
	enc := yaml.NewEncoder(&out)
	enc.SetIndent(2)
	if err := enc.Encode(&doc); err != nil {
		return err
	}
	if err := enc.Close(); err != nil {
		return err
	}
	tmp := path + ".bedctl-tmp"
	if err := os.WriteFile(tmp, out.Bytes(), 0o600); err != nil {
		return err
	}
	return os.Rename(tmp, path)
}

// scalarTagAndStyle picks the YAML tag/style for a replacement scalar:
// numeric values stay plain !!int (a quoted "8080" would break int-typed
// config loading), values containing ':' (listen addresses) stay quoted
// strings, other strings are plain !!str.
func scalarTagAndStyle(v string) (string, yaml.Style) {
	if _, err := strconv.Atoi(v); err == nil {
		return "!!int", 0
	}
	if strings.Contains(v, ":") {
		return "!!str", yaml.DoubleQuotedStyle
	}
	return "!!str", 0
}

// SetServerPort changes server.port in dir/config.yaml, keeping comments.
func SetServerPort(dir string, port int) error {
	return setYAMLValue(dir+"/config.yaml", strconv.Itoa(port), "server", "port")
}

// SetAgentAddr changes the top-level addr in dir/bedrock-agent.yaml.
func SetAgentAddr(dir, addr string) error {
	return setYAMLValue(dir+"/bedrock-agent.yaml", addr, "addr")
}
