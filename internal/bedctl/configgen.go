// flexInt accepts both bare and quoted YAML scalars for numeric fields.
type flexInt int

func (f *flexInt) UnmarshalYAML(node *yaml.Node) error {
	s := strings.TrimSpace(node.Value)
	if s == "" || s == "~" || s == "null" {
		*f = 0
		return nil
	}
	n, err := strconv.Atoi(s)
	if err != nil {
		return fmt.Errorf("行 %d: %q 不是合法端口号", node.Line, node.Value)
	}
	*f = flexInt(n)
	return nil
}

type serverConfigHead struct {
	Server struct {
		Port flexInt `yaml:"port"`
		Host string  `yaml:"host"`
	} `yaml:"server"`
	Database struct {
		Path string `yaml:"path"`
	} `yaml:"database"`
}

// ReadServerPort parses server.port from dir/config.yaml; 0 when absent.
func ReadServerPort(dir string) (int, error) {
	data, err := os.ReadFile(dir + "/config.yaml")
	if err != nil {
		return 0, err
	}
	var head serverConfigHead
	if err := yaml.Unmarshal(data, &head); err != nil {
		return 0, err
	}
	return int(head.Server.Port), nil
}

